#!/usr/bin/env python3
"""Generate scripts/mr-sources/: the Modrinth layer of the pack.

The pack is CurseForge-canonical (mods/, resourcepacks/, shaderpacks/ use `metadata:curseforge`).
`packwiz modrinth export` bundles every CurseForge entry as an override jar, which Modrinth's review
rejects. build-variants.py overlays scripts/mr-sources/ on the pack for the .mrpack export, so each
CurseForge entry is replaced by a direct cdn.modrinth.com link to the same release.

Matching, strongest first:
  1. sha1 lookup (POST /v2/version_files): the identical file is on Modrinth.
  2. Same filename in the mod's Modrinth project (NeoForge 1.21.1 versions). The project comes from
     MR_PROJECT_HINTS or a Modrinth search on the mod's name. Same release, different build bytes.
Anything else is printed as UNRESOLVED: find it on Modrinth (add a hint) or let it ride as an
override and add it to ALLOWED_OVERRIDES in audit-artifacts.py with a reason.

Each generated file records the canonical sha1 it was made from (`# canonical-sha1 = ...`);
build-variants.py refuses to build when that no longer matches (re-run this script after
`packwiz update`). StreamCraft is skipped: build-variants.py handles its per-OS files.

Usage: py -3 scripts/sync-mr-sources.py            (writes scripts/mr-sources/, prints a report)
       py -3 scripts/sync-mr-sources.py --check    (exit 1 if mr-sources/ is missing or stale)
"""
from __future__ import annotations

import argparse, json, re, shutil, sys, urllib.parse, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "scripts" / "mr-sources"
DIRS = ("mods", "resourcepacks", "shaderpacks")
SKIP = {"mods/streamcraft-live.pw.toml"}
API = "https://api.modrinth.com/v2"
UA = {"User-Agent": "slashdaemon/TBA sync-mr-sources", "Content-Type": "application/json"}
LOADER = "neoforge"

# canonical path -> Modrinth project slug/id, for mods whose name search finds the wrong project
MR_PROJECT_HINTS: dict[str, str] = {}

# Not on Modrinth, open licence: these ride as bundled overrides in the .mrpack on purpose
# (each also needs its ALLOWED_OVERRIDES["modrinth"] entry in audit-artifacts.py).
BUNDLED_ON_MODRINTH = {
    "mods/framework.pw.toml": "Framework (MrCrayfish), CurseForge-only, LGPL-2.1",
    "mods/mighty-mail.pw.toml": "Mighty Mail (MrCrayfish), CurseForge-only, MIT",
}

PROJECT_TYPE_LOADERS = {"mods": [LOADER], "resourcepacks": ["minecraft"], "shaderpacks": ["iris", "optifine"]}


def field(text: str, key: str) -> str | None:
    m = re.search(rf'^{key} = "(.*)"$', text, re.M)
    return m.group(1) if m else None


def api(path: str, body: dict | None = None):
    req = urllib.request.Request(API + path, data=json.dumps(body).encode() if body else None, headers=UA)
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def mc_version() -> str:
    return re.search(r'^minecraft = "(.*)"$', (ROOT / "pack.toml").read_text(encoding="utf-8"), re.M).group(1)


def canonical_entries():
    for d in DIRS:
        for p in sorted((ROOT / d).glob("*.pw.toml")):
            rel = p.relative_to(ROOT).as_posix()
            text = p.read_text(encoding="utf-8")
            if rel in SKIP or rel in BUNDLED_ON_MODRINTH or "metadata:curseforge" not in text:
                continue
            if field(text, "hash-format") != "sha1":
                raise SystemExit(f"ERR: {rel} is a CurseForge entry without a sha1 hash")
            yield rel, text


def render(rel: str, canon: str, version: dict, f: dict) -> str:
    return (
        f"# Generated by scripts/sync-mr-sources.py. Do not edit; re-run the script.\n"
        f"# canonical-sha1 = {field(canon, 'hash')}\n"
        f'name = "{field(canon, "name")}"\n'
        f'filename = "{f["filename"]}"\n'
        f'side = "{field(canon, "side") or "both"}"\n\n'
        f"[download]\n"
        f'url = "{f["url"]}"\n'
        f'hash-format = "sha512"\n'
        f'hash = "{f["hashes"]["sha512"]}"\n\n'
        f"[update]\n[update.modrinth]\n"
        f'mod-id = "{version["project_id"]}"\n'
        f'version = "{version["id"]}"\n'
    )


def by_filename(rel: str, canon: str, mc: str):
    """Fallback: the same filename in the mod's Modrinth project."""
    kind = rel.split("/")[0]
    name, filename = field(canon, "name"), field(canon, "filename")
    candidates = [MR_PROJECT_HINTS[rel]] if rel in MR_PROJECT_HINTS else []
    if not candidates:
        facets = json.dumps([[f"versions:{mc}"], [f"project_type:{ {'mods': 'mod', 'resourcepacks': 'resourcepack', 'shaderpacks': 'shader'}[kind] }"]])
        hits = api(f"/search?limit=5&query={urllib.parse.quote(name)}&facets={urllib.parse.quote(facets)}")["hits"]
        candidates = [h["project_id"] for h in hits]
    loaders = urllib.parse.quote(json.dumps(PROJECT_TYPE_LOADERS[kind]))
    gv = urllib.parse.quote(json.dumps([mc]))
    for pid in candidates:
        for v in api(f"/project/{pid}/version?loaders={loaders}&game_versions={gv}"):
            for f in v["files"]:
                if f["filename"] == filename:
                    return v, f
    return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only verify mr-sources/ is complete and current")
    args = ap.parse_args()
    entries = dict(canonical_entries())

    if args.check:
        bad = []
        for rel, canon in entries.items():
            out = OUT / rel
            if not out.exists():
                bad.append(f"missing {rel}")
            elif f"# canonical-sha1 = {field(canon, 'hash')}" not in out.read_text(encoding="utf-8"):
                bad.append(f"stale {rel}")
        for out in OUT.rglob("*.pw.toml"):
            if out.relative_to(OUT).as_posix() not in entries:
                bad.append(f"orphan {out.relative_to(ROOT).as_posix()}")
        print("\n".join(bad) or "mr-sources: current")
        return 1 if bad else 0

    mc = mc_version()
    by_sha1 = {field(t, "hash"): rel for rel, t in entries.items()}
    found = api("/version_files", {"hashes": list(by_sha1), "algorithm": "sha1"})
    results, identical, same_release, unresolved = {}, 0, 0, []
    for sha1, rel in by_sha1.items():
        canon = entries[rel]
        if sha1 in found:
            v = found[sha1]
            f = next(f for f in v["files"] if f["hashes"]["sha1"] == sha1)
            results[rel] = render(rel, canon, v, f)
            identical += 1
            continue
        hit = by_filename(rel, canon, mc)
        if hit:
            results[rel] = render(rel, canon, *hit)
            same_release += 1
        else:
            unresolved.append(rel)

    if OUT.exists():
        shutil.rmtree(OUT)
    for rel, text in results.items():
        p = OUT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")

    print(f"{len(entries)} CurseForge entries: {identical} identical on Modrinth, "
          f"{same_release} same release (different build), {len(unresolved)} unresolved")
    for rel in sorted(unresolved):
        print(f"  UNRESOLVED {rel}  ({field(entries[rel], 'filename')})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
